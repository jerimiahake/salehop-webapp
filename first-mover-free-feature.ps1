# SaleHop update: first-mover incentive -- free "Grant Free Feature" comp
# - Adds a manual, admin-only way to give any pending/approved listing a
#   free one-week Featured placement (skips Stripe entirely) -- meant for
#   an early "first 25 real sellers get a free Featured week" type offer,
#   to help get real, non-Jerimiah-made listings onto the site.
# - New "Grant Free Feature" / "Remove Featured" button on each listing row
#   in /admin (between Reject and Edit). Grant sets featured=true and
#   featured_until = 7 days from now, same fields the paid Stripe flow
#   already sets, so it behaves identically everywhere else in the app.
#   Also permanently marks featured_comp=true on that listing, a one-way
#   historical flag that's never cleared even after the free period ends
#   or is removed -- so the new "Free Comps Given" stat card at the top of
#   /admin always reflects an accurate running count of how many free
#   launch comps have actually gone out.
# - This goes through the same admin-only, service-role PATCH endpoint
#   used everywhere else in /admin (api/admin/sales/[id]), so it's still
#   blocked from being self-triggered by a seller -- only reachable from
#   inside the password-protected admin dashboard.
# - New file: supabase/schema-v9-free-feature-comp.sql (adds the
#   featured_comp column -- run this once in the Supabase SQL Editor).
#   Touches app/api/admin/sales/[id]/route.js (allows featured,
#   featured_until, featured_comp to be written) and app/admin/page.js
#   (the new button, its handlers, and the stat card). No new npm package.

