# SaleHop update: adjustable ad frequency + proximity-based ad ordering
# - Adds a new "Ad frequency" control at the top of the Ads section in
#   /admin: type in how many listings should appear in Browse between each
#   ad card (1-50), click Save. Previously this was a hardcoded constant
#   in the code (every 4th listing) that only I could change.
# - Backed by a new tiny `app_settings` table (schema-v8) so the value
#   persists in Supabase and the live app reads it directly -- no code
#   deploy needed to change it going forward.
# - Ads shown in Browse are now ordered by proximity to whoever's
#   browsing (closest real physical-location ad first -- e.g. Goodwill,
#   Habitat ReStore, any of the physical ads from the recent seed script),
#   with a small random "jitter" of a few miles so similarly-close ads
#   don't always show in the exact same order every time. Online-only ads
#   (no address) don't have a proximity to sort by, so those are just
#   shuffled in after the location-sorted ones. Previously ads just
#   cycled in whatever order Supabase happened to return them in --
#   effectively random and unrelated to distance.
#
# IMPORTANT -- one extra step after running this script: open the
# Supabase SQL Editor and run supabase/schema-v8-ad-frequency-setting.sql
# once (same way you've run every other schema-vN file). That creates the
# table the new admin setting is stored in. If you skip it, the admin
# page still works -- it just falls back to the old fixed "every 4"
# behavior and shows a small note reminding you to run the migration.

